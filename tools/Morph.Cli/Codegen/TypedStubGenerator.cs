using System.Globalization;
using System.Text;
using Morph.Client.Models;

namespace Morph.Cli.Codegen;

public static class TypedStubGenerator
{
    public static string GenerateTypeScript(EffectiveModelDto model)
    {
        var typeName = ToPascal(model.Slug);
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by `morph generate` — do not edit by hand.");
        sb.AppendLine($"// EffectiveModel fingerprint: {model.Fingerprint}");
        sb.AppendLine();
        sb.AppendLine($"export interface {typeName} {{");
        sb.AppendLine("  id: string;");
        foreach (var field in model.Fields)
        {
            var optional = field.IsRequired ? "" : "?";
            sb.AppendLine($"  \"{Escape(field.Path)}\"{optional}: {MapTs(field.DataType)};");
        }

        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"export type {typeName}Create = Omit<{typeName}, \"id\">;");
        sb.AppendLine($"export const {typeName}EntitySlug = \"{model.Slug}\" as const;");
        return sb.ToString();
    }

    public static string GenerateCSharp(EffectiveModelDto model, string ns = "Morph.Generated")
    {
        var typeName = ToPascal(model.Slug);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine($"// EffectiveModel fingerprint: {model.Fingerprint}");
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine($"public sealed class {typeName}");
        sb.AppendLine("{");
        sb.AppendLine("    public Guid Id { get; set; }");
        foreach (var field in model.Fields)
        {
            var prop = ToPascal(field.Path.Replace('.', '_'));
            var clr = MapClr(field.DataType);
            var nullability = field.IsRequired && clr != "string" ? "" : "?";
            sb.AppendLine($"    public {clr}{nullability} {prop} {{ get; set; }}");
        }

        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"public static class {typeName}Entity");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string Slug = \"{model.Slug}\";");
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string MapTs(string dataType) => dataType.ToLowerInvariant() switch
    {
        "string" => "string",
        "int" or "long" or "decimal" => "number",
        "bool" => "boolean",
        "datetime" => "string",
        "guid" or "file" => "string",
        "filearray" => "string[]",
        "json" => "unknown",
        _ => "unknown"
    };

    public static string MapClr(string dataType) => dataType.ToLowerInvariant() switch
    {
        "string" => "string",
        "int" => "int",
        "long" => "long",
        "decimal" => "decimal",
        "bool" => "bool",
        "datetime" => "DateTimeOffset",
        "guid" or "file" => "Guid",
        "filearray" => "Guid[]",
        "json" => "System.Text.Json.JsonElement",
        _ => "object"
    };

    public static string ToPascal(string value)
    {
        var parts = value.Split(['.', '-', '_', '/'], StringSplitOptions.RemoveEmptyEntries);
        var sb = new StringBuilder();
        foreach (var part in parts)
        {
            if (part.Length == 0)
            {
                continue;
            }

            sb.Append(char.ToUpper(part[0], CultureInfo.InvariantCulture));
            if (part.Length > 1)
            {
                sb.Append(part[1..]);
            }
        }

        return sb.Length == 0 ? "Entity" : sb.ToString();
    }

    private static string Escape(string path) => path.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
